    (function() {
        const priceMap = {
            'Straight': {
                '50-75': ' 60,000 -  90,000',
                '75-100': ' 90,000 -  1,20,000',
                '101-125': ' 1,21,200 -  1,50,000',
                '126-150': ' 1,51,200 -  1,80,000',
